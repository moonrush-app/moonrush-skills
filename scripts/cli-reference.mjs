/**
 * docs/cli-reference.md, generated from the CLI's own --help, so the reference cannot drift
 * from the commands. `npm run build` writes it; `node scripts/cli-reference.mjs --check` fails
 * when the committed file is not what the built CLI says (run by prepublishOnly).
 *
 * moonrush.space/ai/docs reads this file from GitHub at build time for its CLI reference.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const OUT = "docs/cli-reference.md";
const help = (args) => execFileSync(process.execPath, ["dist/index.js", ...args], { encoding: "utf8", env: { ...process.env, NO_COLOR: "1" } }).trimEnd();

export function cliReference() {
  const root = help(["--help"]);
  const commands = [...root.matchAll(/^ {2}([a-z]+)\s/gm)].map((m) => m[1]);
  const version = JSON.parse(readFileSync("package.json", "utf8")).version;
  const parts = [
    "<!-- Generated by scripts/cli-reference.mjs from moonrush-cli --help. Do not edit by hand. -->",
    "",
    `Every \`moonrush-cli\` command, as version ${version} prints it. Run any of them with \`--help\` for the same text.`,
    "",
    "## moonrush-cli",
    "",
    "```text",
    root,
    "```",
  ];
  for (const c of commands) {
    parts.push("", `## ${c}`, "", "```text", help([c, "--help"]), "```");
  }
  return parts.join("\n") + "\n";
}

const text = cliReference();
if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== text) {
    console.error(`${OUT} is out of date with the CLI. Run: npm run build`);
    process.exit(1);
  }
  console.log(`${OUT} matches the CLI`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
